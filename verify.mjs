import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://localhost:4317');
await page.waitForSelector('.month', { timeout: 180000 });
const data = await (await page.request.get('http://localhost:4317/api/activity')).json();
assert.equal(Object.values(data.counts).reduce((a,b) => a+b,0), data.total);
assert.equal(await page.locator('#total').textContent(), `${data.total.toLocaleString('en-US')} pull requests`);
await page.screenshot({ path: 'evidence/desktop.png' });
await page.locator('.month').last().hover();
assert.equal(await page.locator('#tooltip').isVisible(), true);
await page.getByRole('button', { name: 'Refresh GitHub activity' }).click();
await page.waitForFunction(() => !document.getElementById('refresh').disabled);
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(250);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
await page.locator('header').click();
await page.screenshot({ path: 'evidence/mobile.png' });
await page.route('**/api/activity', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'GitHub unavailable. Run gh auth status.' }) }));
await page.reload();
await page.waitForFunction(() => document.getElementById('total').textContent.includes('Unable'));
assert.equal(await page.getByRole('button', { name: 'Refresh GitHub activity' }).isEnabled(), true);
await page.unroute('**/api/activity');
await page.getByRole('button', { name: 'Refresh GitHub activity' }).click();
await page.waitForSelector('.month');
await page.route('**/api/activity', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ ...data, total: 0, counts: {} }) }));
await page.reload();
await page.waitForSelector('.month');
assert.equal(await page.locator('#total').textContent(), '0 pull requests');
assert.deepEqual(errors, []);
console.log(JSON.stringify({ total: data.total, months: data.counts, desktop: 'pass', mobile: 'pass', tooltip: 'pass', refresh: 'pass', errorRecovery: 'pass', empty: 'pass', browserErrors: errors }));
await browser.close();
